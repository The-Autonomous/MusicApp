def run(executable, arguments, timeout=30):
    started = time.perf_counter()
    completed = subprocess.run([str(executable), *map(str, arguments)], stdin=subprocess.DEVNULL,
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=timeout,
                               creationflags=CREATE_NO_WINDOW)
    return completed, time.perf_counter() - started


def checked(executable, arguments, timeout=30):
    completed, elapsed = run(executable, arguments, timeout)
    if completed.returncode:
        raise RuntimeError(f"FFmpeg exit {completed.returncode}: {completed.stderr.decode('utf-8', 'replace')[-2400:]}")
    return completed, elapsed


def duration_metadata(executable, path, network_options=()):
    # App metadata fallback deliberately runs -i with no output: exit 1 is normal.
    completed, _ = run(executable, ["-nostdin", "-hide_banner", *network_options, "-rw_timeout", "3000000", "-i", path])
    text = completed.stderr.decode("utf-8", "replace")
    match = re.search(r"Duration:\s*(\d+):(\d+):(\d+(?:\.\d+)?)", text)
    if not match: raise AssertionError(f"Missing app-readable duration metadata: {text[-2000:]}")
    seconds = int(match[1]) * 3600 + int(match[2]) * 60 + float(match[3])
    if seconds <= 0 or not math.isfinite(seconds): raise AssertionError("Invalid duration metadata")
    tags = {}
    for key, value in re.findall(r"^\s*(title|artist)\s*:\s*(.+)$", text, re.I | re.M): tags[key.lower()] = value.strip()
    return {"duration_seconds": seconds, "tags": tags}


def decode(executable, path, seek=0., network_options=()):
    arguments = ["-nostdin", "-hide_banner", "-loglevel", "error", "-threads", "1", "-filter_threads", "1"]
    if str(path).startswith(("http://", "https://")): arguments += [*network_options, "-rw_timeout", "3000000"]
    if seek: arguments += ["-ss", f"{seek:.9f}"]
    arguments += ["-i", str(path), "-vn", "-sn", "-dn", "-map", "0:a:0", "-threads", "1", "-ac", "2", "-ar", "44100", "-f", "f32le", "pipe:1"]
    completed, elapsed = checked(executable, arguments)
    if len(completed.stdout) % 8: raise AssertionError("Decoder output is not interleaved stereo f32le")
    samples = array("f")
    samples.frombytes(completed.stdout)
    if sys.byteorder != "little": samples.byteswap()
    if not samples or not all(math.isfinite(value) for value in samples): raise AssertionError("Empty or nonfinite PCM output")
    rms = math.sqrt(sum(value * value for value in samples) / len(samples))
    if rms < .001: raise AssertionError("Decoded fixture is silent")
    return samples, {"frames": len(samples) // 2, "duration_seconds": len(samples) / (RATE * 2), "rms": rms, "peak": max(map(abs, samples)), "elapsed_seconds": elapsed}


def compare_pcm(reference, candidate, lossy=False, encoded=False):
    expected, expected_info = reference
    actual, actual_info = candidate
    frame_delta = actual_info["frames"] - expected_info["frames"]
    if abs(frame_delta) > 2: raise AssertionError(f"PCM frame counts differ by {frame_delta}: reference={expected_info['frames']} candidate={actual_info['frames']}")
    count = min(len(expected), len(actual))
    squared_error = 0.
    maximum = 0.
    for index in range(count):
        difference = abs(expected[index] - actual[index])
        squared_error += difference * difference
        maximum = max(maximum, difference)
    rmse = math.sqrt(squared_error / count)
    # Same decoder branch should usually be bit-exact. Limits permit small
    # implementation/patch rounding, not a dropped channel or altered resampler.
    rms_limit, peak_limit = (.001, .01) if encoded else ((.0003, .003) if lossy else (.00001, .0001))
    if rmse > rms_limit or maximum > peak_limit:
        raise AssertionError(f"PCM differs: RMSE={rmse:.9g} limit={rms_limit}, peak_error={maximum:.9g} limit={peak_limit}")
    return {"reference": expected_info, "candidate": actual_info, "frame_delta": frame_delta,
            "rmse": rmse, "maximum_error": maximum, "rmse_limit": rms_limit, "maximum_error_limit": peak_limit}


class FixtureServer:
    def __init__(self, directory, tls=None):
        self.directory = directory.resolve()
        self.requests = []
        outer = self
        class Handler(BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.1"
            def log_message(self, *arguments): pass
            def do_HEAD(self): self.send_fixture(False)
            def do_GET(self): self.send_fixture(True)
            def send_fixture(self, body):
                parsed = urlsplit(self.path)
                path = (outer.directory / unquote(parsed.path.lstrip("/"))).resolve()
                if path.parent != outer.directory or not path.is_file(): self.send_error(404); return
                total = path.stat().st_size
                start, end = 0, total - 1
                range_header = self.headers.get("Range", "")
                match = re.fullmatch(r"bytes=(\d+)-(\d*)", range_header)
                if match:
                    start = int(match[1]); end = min(total-1, int(match[2]) if match[2] else total-1)
                    if start >= total or end < start:
                        self.send_response(416); self.send_header("Content-Range", f"bytes */{total}"); self.send_header("Content-Length", "0"); self.end_headers(); return
                outer.requests.append({"path": path.name, "subject": parse_qs(parsed.query).get("subject", ["unknown"])[0], "range": range_header, "start": start, "end": end})
                self.send_response(206 if match else 200)
                self.send_header("Accept-Ranges", "bytes")
                self.send_header("Content-Length", str(end-start+1))
                self.send_header("Content-Type", "application/octet-stream")
                self.send_header("Connection", "close")
                if match: self.send_header("Content-Range", f"bytes {start}-{end}/{total}")
                self.end_headers()
                if body:
                    try:
                        with path.open("rb") as source:
                            source.seek(start); remaining = end-start+1
                            while remaining:
                                block = source.read(min(65536, remaining))
                                if not block: break
                                self.wfile.write(block); remaining -= len(block)
                    except (ConnectionError, ssl.SSLError): pass
        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.server.daemon_threads = True
        if tls:
            context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
            context.load_cert_chain(str(tls[0]), str(tls[1]))
            self.server.socket = context.wrap_socket(self.server.socket, server_side=True)
        self.url = f"{'https' if tls else 'http'}://127.0.0.1:{self.server.server_port}"
        self.worker = threading.Thread(target=self.server.serve_forever, name="fixture-http", daemon=True)
    def __enter__(self): self.worker.start(); return self
    def __exit__(self, *arguments): self.server.shutdown(); self.server.server_close(); self.worker.join(5)


def der_length(length):
    if length < 128: return bytes([length])
    value = length.to_bytes((length.bit_length()+7)//8, "big")
    return bytes([128+len(value)]) + value


def der_integer(value):
    value = value.lstrip(b"\0") or b"\0"
    if value[0] & 128: value = b"\0" + value
    return b"\x02" + der_length(len(value)) + value


def pem(label, contents):
    encoded = base64.b64encode(contents).decode("ascii")
    return f"-----BEGIN {label}-----\n" + "\n".join(encoded[index:index+64] for index in range(0, len(encoded), 64)) + f"\n-----END {label}-----\n"


def make_local_tls(directory):
    """Create test-only keys in memory; no certificate store or trust changes."""
    powershell = shutil.which("pwsh") or shutil.which("powershell")
    if not powershell: raise RuntimeError("PowerShell CertificateRequest API is unavailable")
    command = r"""
$ErrorActionPreference='Stop'
$rsa=[Security.Cryptography.RSA]::Create()
if($rsa -is [Security.Cryptography.RSACryptoServiceProvider]){$rsa.PersistKeyInCsp=$false}
$rsa.KeySize=2048
$request=[Security.Cryptography.X509Certificates.CertificateRequest]::new('CN=localhost',$rsa,[Security.Cryptography.HashAlgorithmName]::SHA256,[Security.Cryptography.RSASignaturePadding]::Pkcs1)
$certificate=$request.CreateSelfSigned([DateTimeOffset]::UtcNow.AddDays(-1),[DateTimeOffset]::UtcNow.AddDays(2))
$p=$rsa.ExportParameters($true)
$data=@{certificate=[Convert]::ToBase64String($certificate.Export([Security.Cryptography.X509Certificates.X509ContentType]::Cert))}
foreach($name in @('Modulus','Exponent','D','P','Q','DP','DQ','InverseQ')){$data[$name]=[Convert]::ToBase64String($p.$name)}
$data|ConvertTo-Json -Compress
$certificate.Dispose();$rsa.Dispose()
"""
    result = subprocess.run([powershell, "-NoProfile", "-NonInteractive", "-Command", command], capture_output=True, timeout=20, creationflags=CREATE_NO_WINDOW)
    if result.returncode: raise RuntimeError(result.stderr.decode("utf-8", "replace")[-1000:])
    values = json.loads(result.stdout.decode("utf-8-sig"))
    integers = [b"\0"] + [base64.b64decode(values[name]) for name in ("Modulus", "Exponent", "D", "P", "Q", "DP", "DQ", "InverseQ")]
    content = b"".join(der_integer(value) for value in integers)
    key = b"\x30" + der_length(len(content)) + content
    certificate_path, key_path = directory / "localhost-fixture-cert.pem", directory / "localhost-fixture-key.pem"
    certificate_path.write_text(pem("CERTIFICATE", base64.b64decode(values["certificate"])), encoding="ascii")
    key_path.write_text(pem("RSA PRIVATE KEY", key), encoding="ascii")
    return certificate_path, key_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference", type=Path, required=True)
    parser.add_argument("--candidate", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--tls", choices=("auto", "required", "off"), default="auto")
    parser.add_argument("--tls-cert", type=Path)
    parser.add_argument("--tls-key", type=Path)
    parser.add_argument("--keep-fixtures", action="store_true")
    args = parser.parse_args()
    args.reference, args.candidate, args.output = args.reference.resolve(), args.candidate.resolve(), args.output.resolve()
    for binary in (args.reference, args.candidate):
        if not binary.is_file(): parser.error(f"Executable missing: {binary}")
    if not args.output.is_relative_to(BASE): parser.error("Output must remain inside rust_musicapp")
    if bool(args.tls_cert) != bool(args.tls_key): parser.error("Supply both --tls-cert and --tls-key")
    args.output.mkdir(parents=True)
    fixtures_directory, converted_directory = args.output / "fixtures", args.output / "converted"
    fixtures_directory.mkdir(); converted_directory.mkdir()
    owned_files = []
    report = {"schema_version": 1, "created_utc": datetime.now(timezone.utc).isoformat(), "tests": [], "errors": [], "optional": [],
              "test_tool_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              "fixture_duration_seconds": DURATION,
              "application_decoder_output": "-vn -sn -dn -map 0:a:0 -threads 1 -ac 2 -ar 44100 -f f32le pipe:1",
              "application_conversion": "-vn -acodec libmp3lame -b:a 192k -id3v2_version 3 -metadata title=... -metadata artist=...",
              "application_cut_filter": FILTER,
              "scope": "Native audio playback and YouTube MP3 conversion compatibility; no accounts, original edits, live sites or executable replacement.",
              "pcm_tolerances": {"frame_delta_maximum": 2, "lossless_rmse": .00001, "lossless_peak_error": .0001, "lossy_rmse": .0003, "lossy_peak_error": .003, "encoded_mp3_rmse": .001, "encoded_mp3_peak_error": .01},
              "tls_scope": "Local fixture handshake only; -tls_verify 0 is used solely for the ephemeral self-signed loopback certificate, never application or global configuration."}
    for kind, binary in (("reference", args.reference), ("candidate", args.candidate)):
        version, _ = checked(binary, ["-version"])
        report[kind] = {"path": str(binary), "sha256": hashlib.sha256(binary.read_bytes()).hexdigest(), "size_bytes": binary.stat().st_size, "version": version.stdout.decode("utf-8", "replace")}
    report["distinct_executables"] = report["reference"]["sha256"] != report["candidate"]["sha256"]

    def record(name, action):
        started = time.perf_counter()
        try:
            details = action()
            report["tests"].append({"name": name, "status": "passed", "elapsed_seconds": time.perf_counter()-started, "details": details})
            print("PASS", name, flush=True)
            return details
        except Exception as error:
            report["tests"].append({"name": name, "status": "failed", "elapsed_seconds": time.perf_counter()-started, "error": str(error)})
            report["errors"].append({"name": name, "error": str(error)})
            print("FAIL", name, str(error)[:240], flush=True)
            return None

    def persist():
        report["passed"] = not report["errors"]
        report["passed_tests"] = sum(test["status"] == "passed" for test in report["tests"])
        report["failed_tests"] = len(report["errors"])
        (args.output / "compatibility.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

    base = fixtures_directory / "source-stereo48.wav"
    owned_files.append(base)
    try:
        checked(args.reference, ["-nostdin", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", f"aevalsrc=0.18*sin(2*PI*440*t)+0.06*sin(2*PI*83*t)|0.18*sin(2*PI*997*t):s=48000:d={DURATION}", "-c:a", "pcm_s16le", base])
        paths = {}
        for fixture in FIXTURES:
            path = fixtures_directory / f"{fixture.name}.{fixture.extension}"
            owned_files.append(path)
            def generate(fixture=fixture, path=path):
                arguments = ["-nostdin", "-hide_banner", "-loglevel", "error", "-y", "-threads", "1", "-filter_threads", "1"]
                if fixture.video:
                    arguments += ["-f", "lavfi", "-i", f"color=c=black:s=64x64:r=5:d={DURATION}", "-i", base, "-map", "0:v:0", "-map", "1:a:0"]
                    arguments += ["-c:v", "libx264", "-preset", "ultrafast"] if fixture.video == "h264" else ["-c:v", "libvpx-vp9", "-deadline", "realtime", "-cpu-used", "8"]
                    arguments += ["-shortest"]
                else: arguments += ["-i", base]
                checked(args.reference, [*arguments, *fixture.options, path])
                paths[fixture.name] = path
                return {"filename": path.name, "bytes": path.stat().st_size, "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "reference_options": list(fixture.options), "video": fixture.video or None}
            if record("generate/" + fixture.name, generate) is None: continue
            for seek in (0., .47, 1.43):
                record(f"decode/{fixture.name}/seek-{seek:g}", lambda fixture=fixture, path=path, seek=seek: compare_pcm(decode(args.reference, path, seek), decode(args.candidate, path, seek), fixture.lossy))
            def metadata_test(path=path):
                expected, actual = duration_metadata(args.reference, path), duration_metadata(args.candidate, path)
                if abs(expected["duration_seconds"]-actual["duration_seconds"]) > .03: raise AssertionError(f"Metadata duration differs: {expected} vs {actual}")
                if path.suffix == ".mp3" and path.name.startswith("tagged"):
                    if actual["tags"].get("title") != TITLE or actual["tags"].get("artist") != ARTIST: raise AssertionError(f"Tagged MP3 metadata was lost: {actual}")
                return {"reference": expected, "candidate": actual}
            record("metadata/" + fixture.name, metadata_test)
            if fixture.transcode:
                for trim in (False, True):
                    def transcode_test(fixture=fixture, path=path, trim=trim):
                        outputs = []
                        for label, binary in (("reference", args.reference), ("candidate", args.candidate)):
                            target = converted_directory / f"{fixture.name}-{int(trim)}-{label}.mp3"
                            owned_files.append(target)
                            arguments = ["-nostdin", "-hide_banner", "-loglevel", "error", "-y", "-threads", "1", "-filter_threads", "1", "-i", path,
                                         "-vn", "-acodec", "libmp3lame", "-b:a", "192k", "-id3v2_version", "3", "-metadata", "title="+TITLE, "-metadata", "artist="+ARTIST]
                            if trim: arguments += ["-af", FILTER]
                            checked(binary, [*arguments, target])
                            header = target.read_bytes()[:10]
                            if header[:3] != b"ID3" or header[3] != 3: raise AssertionError("MP3 output does not contain ID3v2.3")
                            metadata = duration_metadata(args.reference, target)
                            if metadata["tags"].get("title") != TITLE or metadata["tags"].get("artist") != ARTIST: raise AssertionError(f"Output tags missing: {metadata}")
                            outputs.append(decode(args.reference, target))
                        comparison = compare_pcm(outputs[0], outputs[1], encoded=True)
                        if trim and comparison["candidate"]["duration_seconds"] >= DURATION-.25: raise AssertionError("aselect/asetpts did not remove the fixture segments")
                        return comparison
                    record(f"convert/{fixture.name}/{'aselect-asetpts' if trim else 'plain'}", transcode_test)
            persist()

        network_names = ("wav_pcm16_stereo48", "tagged café MP3", "m4a_aac", "webm_opus", "video_h264_aac", "video_vp9_opus")
        def network_suite(server, scheme, options=()):
            for name in network_names:
                if name not in paths: continue
                path = paths[name]
                url = server.url + "/" + quote(path.name)
                for seek in (0., 1.43):
                    def test(url=url, seek=seek, path=path):
                        # Compare BOTH network paths with the same local-file
                        # baseline, so a shared HTTP-seeking bug cannot pass.
                        local = decode(args.reference, path, seek)
                        reference = compare_pcm(local, decode(args.reference, url + "?subject=reference", seek, options), lossy=True)
                        actual = compare_pcm(local, decode(args.candidate, url + "?subject=candidate", seek, options), lossy=True)
                        return {"reference_network": reference, "candidate_network": actual}
                    record(f"{scheme}/{name}/seek-{seek:g}", test)
            def candidate_range_test():
                count = sum(request["subject"] == "candidate" and request["start"] > 0 for request in server.requests)
                if not count: raise AssertionError("Candidate never requested a nonzero byte range while seeking")
                return {"nonzero_range_requests": count}
            record(scheme + "/candidate-nonzero-byte-range-seeks", candidate_range_test)
            return {"request_count": len(server.requests), "range_request_count": sum(bool(request["range"]) for request in server.requests),
                    "nonzero_range_request_count": sum(request["start"] > 0 for request in server.requests), "requests": server.requests}
        with FixtureServer(fixtures_directory) as server:
            report["http"] = network_suite(server, "http")
            if not report["http"]["range_request_count"]: record("http/range-requests-present", lambda: (_ for _ in ()).throw(AssertionError("FFmpeg never requested byte ranges")))
        tls = None
        if args.tls != "off":
            try:
                tls = (args.tls_cert.resolve(), args.tls_key.resolve()) if args.tls_cert else make_local_tls(fixtures_directory)
                if not args.tls_cert: owned_files.extend(tls)
            except Exception as error:
                if args.tls == "required": record("tls/fixture-generation", lambda: (_ for _ in ()).throw(RuntimeError(str(error))))
                else: report["optional"].append({"test": "localhost_tls", "status": "skipped", "reason": str(error)})
        if tls:
            with FixtureServer(fixtures_directory, tls) as server:
                report["https"] = network_suite(server, "https", ("-tls_verify", "0"))
        elif args.tls == "off": report["optional"].append({"test": "localhost_tls", "status": "disabled by --tls off"})
    except Exception as error:
        report["errors"].append({"name": "suite", "error": str(error)})
        print("SUITE ERROR", str(error), flush=True)
    finally:
        persist()
        if not args.keep_fixtures:
            for path in owned_files:
                if path.parent in (fixtures_directory, converted_directory): path.unlink(missing_ok=True)
        summary = f"{'PASS' if report['passed'] else 'FAIL'}: {report['passed_tests']} passed, {report['failed_tests']} failed."
        limitations = "TLS verification bypass is fixture-local only. This does not test real sites, platform trust, DRM, sign-in, playback devices or every possible codec variant."
        (args.output / "README.txt").write_text(summary + "\n" + limitations + "\nSee compatibility.json for every command-family result and numerical differences.\n", encoding="utf-8")
        print(summary, flush=True)
        print(args.output / "compatibility.json", flush=True)
    raise SystemExit(0 if report["passed"] else 1)


if __name__ == "__main__":
    main()
